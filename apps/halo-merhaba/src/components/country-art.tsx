export function CountryOutline({ country }: { country: "id" | "tr" }) {
  return (
    <g className="hm-country-outline" data-country={country}>
      {outlines[country].map((d, index) => (
        <path key={index} d={d} vectorEffect="non-scaling-stroke" />
      ))}
    </g>
  );
}
/** Both national flags use their 3:2 ratio. Colors are explicit, never inherited. */
export function CountryFlag({ country }: { country: "id" | "tr" }) {
  const star = Array.from({ length: 10 }, (_, i) => {
    const angle = (i * Math.PI) / 5;
    const radius = i % 2 === 0 ? 75 : 28.65;
    return `${510 + Math.cos(angle) * radius},${300 + Math.sin(angle) * radius}`;
  }).join(" ");
  return (
    <svg
      className="hm-country-flag"
      viewBox="0 0 900 600"
      aria-hidden="true"
      focusable="false"
      data-flag={country}
    >
      {country === "id" ? (
        <>
          <path fill="#FF0000" stroke="none" d="M0 0h900v300H0Z" />
          <path fill="#FFFFFF" stroke="none" d="M0 300h900v300H0Z" />
        </>
      ) : (
        <>
          <path fill="#E30A17" stroke="none" d="M0 0h900v600H0Z" />
          <circle fill="#FFFFFF" stroke="none" cx="300" cy="300" r="150" />
          <circle fill="#E30A17" stroke="none" cx="337.5" cy="300" r="120" />
          <polygon fill="#FFFFFF" stroke="none" points={star} />
        </>
      )}
    </svg>
  );
}
export function FlagPair() {
  return (
    <span className="hm-flag-pair" aria-hidden="true">
      <CountryFlag country="id" />
      <span>↔</span>
      <CountryFlag country="tr" />
    </span>
  );
}
